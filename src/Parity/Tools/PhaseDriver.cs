using System.Text;
using System.Text.RegularExpressions;

namespace Parity.Tools;

/// <summary>
/// The script behind <c>parity init --phase-driver</c>: each phase of the kit runs as its own headless agent process, so every
/// phase starts a fresh session, with legacy/.phase set first and the phase's prompt. Generated from the kit's phase list, so a new
/// phase (or a changed prompt) in adopt/kit.json shows up in the next <c>init</c> without a code change.
/// </summary>
public static class PhaseDriver
{
    public const string Name = "run-phases";

    /// <summary>The script's repo-relative path: next to the .phase file.</summary>
    public static string ScriptPath(KitManifest kit, string ext) => Dir(kit) is { Length: > 0 } d ? $"{d}/{Name}.{ext}" : $"{Name}.{ext}";

    static string Dir(KitManifest kit) => kit.PhaseFile.Contains('/') ? kit.PhaseFile[..kit.PhaseFile.LastIndexOf('/')] : "";

    /// <summary>A double-quoted sh string for text with {module} and {form} placeholders.</summary>
    static string Quote(string text)
    {
        var sb = new StringBuilder("\"");
        foreach (var part in Regex.Split(text, @"(\{module\}|\{form\})"))
        {
            if (part == "{module}") sb.Append("${module}");
            else if (part == "{form}") sb.Append("${form}");
            else foreach (var c in part) sb.Append(c is '\\' or '"' or '$' or '`' ? "\\" + c : c.ToString());
        }
        return sb.Append('"').ToString();
    }

    public static string Sh(KitManifest kit)
    {
        var driven = kit.Phases.Where(p => p.Driven && p.Prompt != null).ToList();
        var names = string.Join(" ", driven.Select(p => p.Name));
        var up = string.Concat(Enumerable.Repeat("../", Dir(kit).Split('/', StringSplitOptions.RemoveEmptyEntries).Length));
        var script = ScriptPath(kit, "sh");
        var sb = new StringBuilder();
        void L(string s = "") => sb.Append(s).Append('\n');
        L("#!/bin/sh");
        L("# Generated by 'parity init --phase-driver' from adopt/kit.json; 'parity init --merge' rewrites it. Do not edit.");
        L("# Runs each phase as a fresh headless agent session: sets the phase file, then starts the agent with that phase's prompt.");
        L($"# usage: sh {script} <Module> <Form> [phase ...]     phases: {names} (default: all, in that order)");
        L("# PARITY_AGENT is the headless command, default 'claude -p'; the prompt is its last argument.");
        L("# A phase that needs a person (recording fixtures, reviewing the spec) ends the run; start it again with the rest,");
        L("# or set PARITY_NO_PAUSE=1 when that step is already done to run straight through.");
        L("set -u");
        L("");
        L("prompt_for() {");
        L("  case $1 in");
        foreach (var p in driven) L($"    {p.Name}) printf '%s' {Quote(p.Prompt!)} ;;");
        L("    *) return 1 ;;");
        L("  esac");
        L("}");
        L("");
        L("pause_for() {");
        L("  case $1 in");
        foreach (var p in driven.Where(p => p.Pause != null)) L($"    {p.Name}) printf '%s' {Quote(p.Pause!)} ;;");
        L("  esac");
        L("}");
        L("");
        L($"[ $# -ge 2 ] || {{ echo \"usage: sh {script} <Module> <Form> [phase ...]   phases: {names}\" >&2; exit 2; }}");
        L("module=$1");
        L("form=$2");
        L("shift 2");
        L($"[ $# -gt 0 ] || set -- {names}");
        L("for phase in \"$@\"; do");
        L($"  prompt_for \"$phase\" >/dev/null || {{ echo \"parity: '$phase' is not a driven phase (driven: {names})\" >&2; exit 2; }}");
        L("done");
        L("");
        L($"cd \"$(dirname \"$0\")/{(up.Length > 0 ? up.TrimEnd('/') : ".")}\" || exit 1");
        L("agent=${PARITY_AGENT:-claude -p}");
        L("");
        L("while [ $# -gt 0 ]; do");
        L("  phase=$1");
        L("  shift");
        L($"  printf '%s\\n' \"$phase\" > {kit.PhaseFile}");
        L("  echo \"== $phase: $form of $module (fresh session)\"");
        L("  # shellcheck disable=SC2086");
        L("  $agent \"$(prompt_for \"$phase\")\" || { echo \"parity: the $phase session failed\" >&2; exit 1; }");
        L("  msg=$(pause_for \"$phase\")");
        L("  if [ $# -gt 0 ] && [ -n \"$msg\" ]; then");
        L("    if [ -n \"${PARITY_NO_PAUSE:-}\" ]; then echo \"== after $phase (PARITY_NO_PAUSE is set, not stopping): $msg\"; continue; fi");
        L("    echo \"== stopped after $phase: $msg\"");
        L($"    echo \"== then: sh {script} $module $form $*\"");
        L("    exit 0");
        L("  fi");
        L("done");
        return sb.ToString();
    }

    /// <summary>The Windows counterpart: the same driver through the sh that the hooks already need (Git for Windows).</summary>
    public static string Cmd(KitManifest kit)
    {
        var dir = Dir(kit).Replace('/', '\\');
        var lines = new[]
        {
            "@echo off",
            "rem Generated by 'parity init --phase-driver'. Windows wrapper: the driver is POSIX sh, like the hooks (Git for Windows).",
            $"rem usage: {dir}{(dir.Length > 0 ? "\\" : "")}{Name}.cmd <Module> <Form> [phase ...]",
            $"sh \"%~dp0{Name}.sh\" %*",
            "exit /b %ERRORLEVEL%",
        };
        return string.Join("\r\n", lines) + "\r\n";
    }
}
